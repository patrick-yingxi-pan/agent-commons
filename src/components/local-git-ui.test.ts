test('Git comparison copies share captured input, receipt recovery and conversation-only authority', () => {
  const review = source('src/components/LocalGitReview.tsx')
  const picker = source('src/components/LocalGitConnections.tsx')
  const repo = source('src/components/RepoContextPicker.tsx')
  const canonical = picker.slice(picker.indexOf('export function LocalGitDetail('))
  assert.ok(!canonical.includes('onAttach='), 'canonical review never grants conversation mutation')
  assert.ok(picker.includes('Review changes in ${connection.name}'))
  assert.ok(picker.includes("isAttached={receipt => isAttached(receipt, 'git-review')} onAttach={attachSavedCopy}"))
  assert.ok(repo.includes("acknowledgedIds(intentScope, attachments.map(item => item.id), 'git-review')"))
  assert.ok(review.includes('prepareGitComparisonCopy({ review: result, comparison: state.comparison, path, previousPath, readAt: state.readAt, repositoryName: name })'))
  assert.ok(review.includes('gitComparisonReceipts.receipt(result, state.comparison, path, previousPath)'))
  assert.ok(review.includes('const live = localGitReviews.get(id)'))
  assert.ok(review.includes('live.result === result') && review.includes('live.comparison === state.comparison && live.path === state.path'))
  assert.ok(review.includes('selectedReceipt.current === candidate'), 'grouping changes fence the rendered copy intent')
  assert.ok(review.includes('connections.rows.some(row => row.id === id)'), 'disconnected source cannot prepare a new attachment')
  assert.ok(review.includes('!connections.busy'), 'pending access changes fence preparation')
  assert.ok(source('src/controller/localGitReviews.ts').includes('localGitConnections.subscribeDisconnect(id => localGitReviews.dismiss(id))'), 'Disconnect retires review immediately, before native acknowledgement')
  assert.ok(review.includes('subscribeCurrent={listener => localGitReviews.subscribe(id, listener)}'))
  assert.ok(review.includes('onAttach && intentScope && <div data-git-comparison-copy'))
  assert.ok(review.includes('<LocalSavedCopyAction source="git-review"'))
  assert.ok(review.includes('snapshot: { text: copy.text }'))
  assert.ok(review.includes('data-git-comparison-copy-text') && review.includes('{copy.text}</pre>'))
  assert.ok(review.includes('Nothing was truncated or attached'))
  assert.ok(!/new File|fetch\(|captureLocalGit|localFileSavedCopy\.submit/.test(review), 'review delegates saved-copy work without a second mutation path')
})

