/** Structural lock for the explicit, owner-funded delegated judgment funnel. */
import test from 'node:test'
import assert from 'node:assert/strict'
import { join } from 'node:path'
import { read, ROOT, stripComments } from '../../tests/helpers/source.ts'

test('delegated judgment pins the owner grant, reviewer, versions and receipt', () => {
  const view = stripComments(read(join(ROOT, 'src/components/SectionView.tsx')))
  const panel = stripComments(read(join(ROOT, 'src/components/DelegatedJudgmentPanel.tsx')))
  const deferred = stripComments(read(join(ROOT, 'src/components/DeferredDelegatedJudgmentPanel.tsx')))
  const commands = stripComments(read(join(ROOT, 'src/api/delegatedJudgmentCommands.ts')))
  const facade = stripComments(read(join(ROOT, 'src/controller/delegatedJudgmentMutations.ts')))
  const runtime = stripComments(read(join(ROOT, 'src/controller/delegatedJudgmentMutationRuntime.ts')))
  const notice = stripComments(read(join(ROOT, 'src/components/DelegatedJudgmentMutationNotice.tsx')))
  const shell = stripComments(read(join(ROOT, 'src/components/ShellMutationNotices.tsx')))
  const legacyCommands = stripComments(read(join(ROOT, 'src/api/commands.ts')))

  assert.equal(legacyCommands.includes('export async function runDelegation'), false)
  assert.ok(view.includes('useDelegatedJudgmentStatus()'))
  assert.ok(view.includes("c?.judgments?.some((run) => run.status === 'pending')"))
  assert.ok(view.includes('delegatedJudgmentHeld || delegatedJudgmentPending'))
  assert.ok(view.includes('<DeferredDelegatedJudgmentPanel'))
  assert.equal(view.includes('Ask ${delegationAction.agentLabel}'), false)
  assert.ok(view.includes("ev.kind === 'delegated-decline'"))
  assert.ok(view.includes('declined within policy'))
  assert.ok(view.includes('disabled={commentHeld}'), 'timeline commentary stays independent')

  assert.ok(panel.includes('project.own === true'), 'only the current Project owner may start')
  assert.ok(panel.includes('delegation.mine !== true'), 'only a grant owned by this delegator is selectable')
  assert.ok(panel.includes('const effectiveSelectedDelegationId = applicable.some'), 'the select value is normalized to currently applicable grants')
  assert.ok(panel.includes('const delegation = applicable.find((candidate) => candidate.id === chosenId)'), 'preview and canStart derive from the same applicable grant')
  assert.ok(panel.includes('delegationsQuery.data !== undefined'), 'a stale selection clears only after roster data exists')
  assert.ok(panel.includes('value={effectiveSelectedDelegationId}'), 'an approved envelope cannot leave the old policy selected')
  assert.ok(panel.includes('agent.tenantId === identity?.tenant.id'), 'shared Agents are not reviewer choices')
  assert.ok(panel.includes('contributionReviewSelections(agents, providers, identity?.tenant.id)'))
  assert.ok(panel.includes('expectedDelegationRevision: selected.revision ?? 0'))
  assert.ok(panel.includes('expectedChangesetVersion: contribution.changeset?.at(-1)?.version ?? null'))
  assert.ok(panel.includes('expectedEnvelopeVersion: contribution.envelope?.version ?? null'))
  assert.ok(panel.includes('agentRevision: agent.revision ?? 0'))
  assert.ok(panel.includes('providerRevision: provider.definitionRevision ?? 0'))
  assert.ok(panel.includes('connectionRevision: provider.connectionRevision ?? 0'))
  assert.ok(panel.includes('Run judgment · uses budget'))
  assert.ok(panel.includes('no tools: it cannot execute external effects'))
  assert.ok(panel.includes('will not be replayed automatically'))
  assert.ok(panel.includes('run.summary && owner'), 'private prose is owner-only')
  assert.ok(panel.includes("run.status === 'pending'"), 'pending receipts disable new runs')
  assert.ok(panel.includes('data-delegated-judgment-status={run.status}'))
  assert.ok(panel.includes('data-delegated-judgment-held'))
  assert.ok(deferred.includes('prepareDelegatedJudgmentRuntime()'), 'the write runtime is ready before form input')
  assert.ok(deferred.includes('Loading this panel never sends a request'))

  assert.ok(facade.includes('const existing = held.get(key)'))
  assert.ok(facade.includes('judgment: { ...input.judgment, reviewer: { ...input.judgment.reviewer } }'))
  assert.ok(facade.includes('intentId: crypto.randomUUID()'))
  assert.ok(facade.includes('held.clear()'), 'account disposal clears held private intent')
  assert.ok(facade.includes('createRetryableRuntimeLoader'))
  assert.ok(commands.includes('{ judgment: { ...intent.judgment, reviewer: { ...intent.judgment.reviewer } } }'))
  assert.ok(commands.includes('run.id === expectedId'))
  assert.ok(commands.includes('run.delegationRevision === intent.judgment.expectedDelegationRevision'))
  assert.ok(commands.includes('run.changesetVersion === intent.judgment.expectedChangesetVersion'))
  assert.ok(commands.includes('run.envelopeVersion === intent.judgment.expectedEnvelopeVersion'))
  assert.ok(commands.includes('run.reviewer === intent.reviewerLabel'))
  assert.ok(commands.includes('run.provider === intent.providerLabel'))
  assert.ok(commands.includes('run.model === intent.modelId'), 'receipt identity uses the resolved model id, not its display label')
  assert.ok(commands.includes("candidate.envelope.status === 'proposed'"), 'a delayed approval cannot rewind already-approved envelope usage')
  assert.ok(commands.includes('judgments: mergeRun(candidate.judgments ?? [], receipt)'))
  assert.ok(runtime.includes('discardReconcileFailure: \'retain\''), 'unknown state stays held on failed dismissal read')
  assert.ok(runtime.includes('mintIdempotencyKey: (intent) => intent.intentId'))
  assert.ok(notice.includes('kind="delegated-judgment"'))
  assert.ok(shell.includes('<DelegatedJudgmentMutationNotice />'))
})
