import { test } from 'node:test'
import assert from 'node:assert/strict'
import { join } from 'node:path'
import { ROOT, read, stripComments } from '../../tests/helpers/source.ts'

const source = (path: string) => stripComments(read(join(ROOT, path)))

test('repository detail places an explicit lazy file browser before change review', () => {
  const detail = source('src/components/LocalGitConnections.tsx')
  assert.ok(detail.includes("lazy(() => import('./LocalGitBrowser.tsx')"))
  assert.ok(detail.lastIndexOf('<LocalGitBrowser id={connection.id}') < detail.indexOf('<LocalGitReview id={connection.id}'))
  const browserUse = detail.slice(detail.lastIndexOf('<LocalGitBrowser id={connection.id}'), detail.indexOf('<LocalGitReview id={connection.id}'))
  assert.ok(!browserUse.includes('onAttach='), 'repository detail browser cannot attach context')
  assert.ok(detail.includes('Browse files in ${connection.name}'))
  assert.ok(detail.includes('onAttach={allowSavedCopy ? (file: PreparedLocalFileSavedCopy) => {'))
  assert.ok(detail.includes('allowSavedCopy: boolean'))
  assert.ok(detail.includes("isAttached={(receipt, sourceKind = 'git') => {"))
  assert.ok(detail.includes('attachments.some(item => item.id === id)'))
  assert.ok(detail.includes('id: file.id, label: file.name, kind: file.kind'))
  assert.ok(detail.includes('if (attachments.some(item => item.id === file.id)) return'))
  assert.ok(detail.includes("...(file.kind === 'file' ? { previewText: file.text } : { image: file.image })"))
  assert.ok(detail.includes('...(file.documentImport && { documentImport: file.documentImport })'))
  assert.ok(detail.includes('source: UI_HOST_SOURCE,'), 'the attachment receives the prepared UI-host file')
  assert.ok(!/onAttach=\{[^}]*readLocalGitFile/.test(detail), 'attachment never rereads the native source')
})

