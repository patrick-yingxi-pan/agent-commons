import { test } from 'node:test'
import assert from 'node:assert/strict'
import { join } from 'node:path'
import { ROOT, read, stripComments } from '../../tests/helpers/source.ts'

const source = (path: string) => stripComments(read(join(ROOT, path)))

test('repository detail places an explicit lazy file browser before change review', () => {
  const detail = source('src/components/LocalGitConnections.tsx')
  assert.ok(detail.includes("lazy(() => import('./LocalGitBrowser.tsx')"))
  assert.ok(detail.lastIndexOf('<LocalGitBrowser id={connection.id}') < detail.indexOf('<LocalGitReview id={connection.id}'))
  const browserUse = detail.slice(detail.lastIndexOf('<LocalGitBrowser id={connection.id}'), detail.indexOf('<LocalGitReview id={connection.id}'))
  assert.ok(!browserUse.includes('onAttach='), 'repository detail browser cannot attach context')
  assert.ok(detail.includes('Browse files in ${connection.name}'))
  assert.ok(detail.includes('onAttach={allowSavedCopy ? (path, text, receipt) => {'))
  assert.ok(detail.includes('allowSavedCopy: boolean'))
  assert.ok(detail.includes('isAttached={receipt => {'))
  assert.ok(detail.includes('attachments.some(item => item.id === id)'))
  assert.ok(detail.includes("id, label: path, kind: 'file', source: UI_HOST_SOURCE, previewText: text"))
  assert.ok(detail.includes('if (attachments.some(item => item.id === id)) return'))
  assert.ok(detail.includes('previewText: text'))
  assert.ok(detail.includes("source: UI_HOST_SOURCE, previewText: text"), 'the attachment receives only the saved preview copy')
  assert.ok(!/onAttach=\{[^}]*readLocalGitFile/.test(detail), 'attachment never rereads the native source')
})

test('browser waits for explicit listing and per-path preview; source content is exact and bounded', () => {
  const browser = source('src/components/LocalGitBrowser.tsx')
  assert.ok(browser.includes("onClick={() => { setQuery(''); setPage(0); void localGitBrowser.readListing(id) }}"))
  assert.ok(browser.includes('Listing reads bounded Git metadata and applicable ignore files'))
  assert.ok(browser.indexOf('<details') < browser.indexOf('{listing &&'), 'limits and privacy disclosure remains available before a successful listing')
  assert.ok(browser.includes('Bounded Git metadata and applicable ignore files are read to compute it'))
  assert.ok(browser.includes('it does not preview tracked file contents'))
  assert.ok(browser.includes("state.listingStatus === 'loading' || state.listingStatus === 'error'"), 'Dismiss stays available during an initial read')
  assert.ok(browser.includes('localGitBrowser.readPreview(id, file.path)'))
  assert.ok(browser.includes('const PAGE_SIZE = 100'))
  assert.ok(browser.includes('.filter(file => !needle || file.path.toLocaleLowerCase().includes(needle))'))
  assert.ok(browser.includes('listing.files.length} tracked paths'))
  assert.ok(browser.includes('file.kind === \'conflict\' ? \'Conflict\''))
  assert.ok(browser.includes('file.kind === \'sparse\' ? \'Sparse checkout\''))
  assert.ok(browser.includes('file.kind === \'file\' ? \'Tracked file\' : file.kind === \'conflict\''))
  assert.ok(browser.includes('role="region" aria-label={`Preview of ${state.preview.path}`}'))
  assert.ok(browser.includes('state.preview.snapshot.text}</pre>'))
  assert.ok(browser.includes("const previewText = state.preview?.snapshot && 'text' in state.preview.snapshot ? state.preview.snapshot.text : null"))
  assert.ok(browser.includes('Empty file (0 bytes).'))
  assert.ok(browser.includes('previewText === null'), 'only a real text preview including empty text is attachable')
  assert.ok(browser.includes('await onAttach(path, previewText, receipt)'), 'saved-copy action waits for the ordinary context flow acknowledgement')
  assert.ok(browser.includes('isAttached?.(receipt)'), 'added feedback comes from the acknowledged attachment projection')
  assert.ok(browser.includes('useLocalGitSavedCopyPending(intentScope, id, receipt)'), 'pending state survives picker remount in memory')
  assert.ok(browser.includes('attachingRef.current || previewAttached'), 'a repeated click cannot enqueue the same preview while its first attach is held')
  assert.ok(browser.includes("previewAttached ? 'Added' : attachWaiting ? 'Saving saved copy…' : 'Attach saved copy'"))
  assert.ok(browser.includes('attachWaiting || previewAttached'))
  assert.ok(browser.includes('attachError && <p role="alert"'))
  assert.ok(!browser.includes('acknowledgedKey'), 'saved feedback has no local success latch that can outlive a detached attachment')
  const attachControl = browser.slice(browser.indexOf('const attachSavedCopy'), browser.indexOf('return <section'))
  assert.ok(!attachControl.includes('readPreview'), 'Attach saved copy never triggers another source read')
  assert.ok(browser.includes('whole-file limit 65,536 bytes'))
  assert.ok(browser.includes('It is available to model input when the conversation is next sent; attaching does not send a message or call the model.'))
  assert.ok(!/useEffect|localStorage|fetch\(|captureLocalGit/.test(browser))
})
