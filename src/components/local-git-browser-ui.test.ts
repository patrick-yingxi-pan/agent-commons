import { test } from 'node:test'
import assert from 'node:assert/strict'
import { join } from 'node:path'
import { ROOT, read, stripComments } from '../../tests/helpers/source.ts'

const source = (path: string) => stripComments(read(join(ROOT, path)))

test('repository detail places an explicit lazy file browser before change review', () => {
  const detail = source('src/components/LocalGitConnections.tsx')
  assert.ok(detail.includes("lazy(() => import('./LocalGitBrowser.tsx')"))
  assert.ok(detail.lastIndexOf('<LocalGitBrowser id={connection.id}') < detail.indexOf('<LocalGitReview id={connection.id}'))
  const browserUse = detail.slice(detail.lastIndexOf('<LocalGitBrowser id={connection.id}'), detail.indexOf('<LocalGitReview id={connection.id}'))
  assert.ok(!browserUse.includes('onAttach='), 'repository detail browser cannot attach context')
  assert.ok(detail.includes('Browse files in ${connection.name}'))
  assert.ok(detail.includes('onAttach={allowSavedCopy ? (path, text, receipt, documentImport) => {'))
  assert.ok(detail.includes('allowSavedCopy: boolean'))
  assert.ok(detail.includes('isAttached={receipt => {'))
  assert.ok(detail.includes('attachments.some(item => item.id === id)'))
  assert.ok(detail.includes("id, label: path, kind: 'file', source: UI_HOST_SOURCE, previewText: text"))
  assert.ok(detail.includes('if (attachments.some(item => item.id === id)) return'))
  assert.ok(detail.includes('previewText: text'))
  assert.ok(detail.includes("source: UI_HOST_SOURCE, previewText: text"), 'the attachment receives only the saved preview copy')
  assert.ok(!/onAttach=\{[^}]*readLocalGitFile/.test(detail), 'attachment never rereads the native source')
})

test('browser waits for explicit listing and per-path preview; source content is exact and bounded', () => {
  const browser = source('src/components/LocalGitBrowser.tsx')
  const shared = source('src/components/LocalFileBrowserView.tsx')
  assert.ok(browser.includes('localGitBrowser.readListing(id)') && browser.includes('readPreview={path => localGitBrowser.readPreview(id, path)}'))
  assert.ok(browser.includes('Listing reads bounded Git metadata and applicable ignore files'))
  assert.ok(browser.includes('refreshLabel="Refresh tracked paths"'))
  assert.ok(browser.includes('loadingStatusCopy="Reading bounded tracked-path metadata'))
  assert.ok(browser.includes('Bounded Git metadata and applicable ignore files are read to compute it'))
  assert.ok(browser.indexOf('<details') < shared.indexOf('{listing &&'), 'limits and privacy disclosure remains available before a successful listing')
  assert.ok(shared.includes('(listing || state.listingStatus === \'loading\' || state.listingStatus === \'error\')'), 'Dismiss stays available during initial listing')
  assert.ok(shared.includes('const PAGE_SIZE = 100'))
  assert.ok(shared.includes('.filter(file => !needle || file.path.toLocaleLowerCase().includes(needle))'))
  assert.ok(shared.includes('entryLabel(file)'))
  assert.ok(browser.includes("entry.kind === 'conflict' ? 'Conflict'"))
  assert.ok(browser.includes("entry.kind === 'sparse' ? 'Sparse checkout'"))
  assert.ok(shared.includes('role="region" aria-label={`Preview of ${state.preview.path}`}'))
  assert.ok(shared.includes('{state.preview.snapshot.text}</pre>'))
  assert.ok(shared.includes("'text' in state.preview.snapshot ? state.preview.snapshot.text : null"))
  assert.ok(shared.includes('Empty file (0 bytes).'))
  assert.ok(shared.includes('previewText === null'), 'only a real text preview including empty text is attachable')
  assert.ok(shared.includes('await onAttach(path, previewText, receipt, state.preview.documentImport)'), 'saved-copy action preserves fidelity metadata and waits for the ordinary context flow acknowledgement')
  assert.ok(shared.includes('isAttached?.(receipt)'), 'added feedback comes from acknowledged attachment projection')
  assert.ok(shared.includes('useLocalGitSavedCopyPending(intentScope, connectionId, receipt, source)'), 'pending state survives picker remount in source-qualified memory')
  assert.ok(shared.includes('attachingRef.current || previewAttached'))
  assert.ok(shared.includes("previewAttached ? 'Added' : attachWaiting ? 'Saving saved copy…' : 'Attach saved copy'"))
  assert.ok(shared.includes('attachWaiting || previewAttached'))
  assert.ok(shared.includes('attachError && <p role="alert"'))
  assert.ok(shared.includes('whole-file limit 65,536 bytes'))
  assert.ok(browser.includes('It is available to model input when the conversation is next sent; attaching does not send a message or call the model.'))
  assert.ok(shared.includes('outsideListingPrivacyCopy'))
  assert.ok(shared.includes('{outsideListingPrivacyCopy}'))
  assert.ok(!/useEffect|localStorage|fetch\(|captureLocalGit/.test(shared + browser))
})
