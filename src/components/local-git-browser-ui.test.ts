test('untracked Git intake requires transient opt-in then an explicit listing and keeps conversation attachment source-qualified', () => {
  const browser = source('src/components/LocalGitBrowser.tsx')
  const controller = source('src/controller/localGitUntrackedBrowser.ts')
  const optIn = source('src/controller/localGitUntrackedOptInCore.ts')
  const repo = source('src/components/RepoContextPicker.tsx')
  assert.ok(browser.includes('Browse untracked files'))
  assert.ok(browser.includes('List untracked paths'))
  assert.ok(browser.includes('onToggle={() => localGitUntrackedOptIn.set(id, !untrackedEnabled)}'))
  assert.ok(browser.includes('readListing={() => localGitUntrackedBrowser.readListing(id)}'))
  assert.ok(browser.includes('localGitUntrackedBrowser.get(id).previewReceipt === receipt'), 'untracked cancellation checks the live receipt rather than the render snapshot')
  assert.ok(browser.includes('localGitUntrackedOptIn.get(id) && localGitUntrackedBrowser.get(id).previewReceipt === receipt'), 'disabling untracked intake fences an upload before context publication')
  assert.ok(browser.includes('Untracked files can include new files and dotfiles with secrets. Ignored candidates are excluded; each ignored directory counts once.'))
  assert.ok(controller.includes('readLocalGitUntrackedFiles(id, signal)'))
  assert.ok(controller.includes('readLocalGitUntrackedFile(id, path, signal)'))
  assert.ok(controller.includes('localGitUntrackedOptIn.clear()'))
  assert.ok(controller.includes('localGitUntrackedOptIn.set(id, false)'))
  assert.ok(optIn.includes('onDisable(id)'))
  assert.ok(repo.includes("acknowledgedIds(intentScope, attachments.map(item => item.id), 'git-untracked')"), 'repo footer includes acknowledged untracked saved copies')
  assert.ok(browser.includes('source="git-untracked"'))
  assert.ok(browser.includes('listAria="Untracked repository paths"'))
  assert.ok(browser.includes('limitsLabel="Untracked listing limits"'), 'compact untracked view keeps its own reachable limit disclosure')
  assert.ok(browser.includes('10,000 raw directory entries, 1,024 visited directories, depth 64, or 1 MiB of candidate-path bytes'))
  assert.ok(browser.includes('ignored candidate entries excluded (each ignored directory counts once; unseen contents are not counted)'), 'excluded count cannot imply unseen ignored directory contents')
  assert.ok(browser.includes('headingLevel={3}'), 'the untracked heading nests below the tracked browser heading')
  assert.ok(browser.includes('afterContent={untrackedContent}'), 'untracked section is nested inside the tracked browser section')
  assert.ok(source('src/components/LocalFileBrowserView.tsx').includes('{afterContent}'))
  assert.ok(browser.includes('onAttach={onAttach}'), 'untracked preview reuses the exact saved-copy callback without rereading')
})
