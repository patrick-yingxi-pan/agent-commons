import { test } from 'node:test'
import assert from 'node:assert/strict'
import { join } from 'node:path'
import { read, ROOT, stripComments } from '../../tests/helpers/source.ts'

const source = (path: string) => stripComments(read(join(ROOT, path)))

test('local folder detail and picker expose explicit lazy listing and path preview without automatic reads', () => {
  const detail = source('src/components/LocalFolderConnections.tsx')
  const view = source('src/components/LocalFileBrowserView.tsx')
  const wrapper = source('src/components/LocalFolderBrowser.tsx')
  assert.ok(detail.includes("lazy(() => import('./LocalFolderBrowser.tsx')"))
  assert.ok(detail.includes('<LocalFolderBrowser id={connection.id} name={connection.name} enabled={state.status === \'ready\' && !state.busy} />'))
  assert.ok(!/useEffect\([^)]*readListing|onClick=\{[^}]*readListing/.test(detail), 'mounting the detail never lists or previews')
  assert.ok(wrapper.includes('localFolderBrowser.readListing(id)'))
  assert.ok(wrapper.includes('localFolderBrowser.readPreview(id, path)'))
  assert.ok(wrapper.includes('listing.files.length} visible paths'))
  assert.ok(wrapper.includes('listing.directoryCount} directories'))
  assert.ok(wrapper.includes('listing.hiddenCount} hidden paths excluded'))
  assert.ok(wrapper.includes('64 directories'))
  assert.ok(wrapper.includes('refreshLabel="Refresh folder paths"'))
  assert.ok(wrapper.includes('loadingStatusCopy="Listing folder paths'))
  assert.ok(view.includes('{loadingStatusCopy}'))
  assert.ok(view.includes("'data-local-folder-browser': ''"))
  assert.ok(view.includes('data-local-folder-browser-listing={folder ?'))
  assert.ok(view.includes("'data-local-folder-file-preview': ''"))
  assert.ok(view.includes('const PAGE_SIZE = 100'))
  assert.ok(wrapper.includes('Listing is bounded to 16 levels, 64 directories, and 500 entries. Hidden paths are excluded and counted.'))
  assert.ok(view.includes('listingSummary(listing, state.listingReadAt)'), 'source-specific exclusion metadata is rendered by its wrapper')
  assert.ok(view.includes('file.kind !== \'file\''), 'unsupported entries remain visible but cannot be previewed')
  assert.ok(view.includes('state.preview.snapshot.text}</pre>'))
  assert.ok(view.includes('Empty file (0 bytes).'))
  assert.ok(view.includes('Attach saved copy'))
  assert.ok(view.includes('Dismiss'))
  assert.ok(!/useEffect|localStorage|fetch\(|captureLocalFolder/.test(view + wrapper))
})

test('local folder picker preserves whole-copy attach only for conversation and scopes exact preview receipts', () => {
  const picker = source('src/components/LocalFolderConnections.tsx')
  const workflow = source('src/components/ContextPickerWorkflow.tsx')
  assert.ok(picker.includes('allowSavedCopies = true'))
  assert.ok(picker.includes('if (!allowSavedCopies || busy.current'))
  assert.ok(picker.includes('{allowSavedCopies && <button type="button" aria-label={`Attach ${connection.name}`}'))
  assert.ok(picker.includes('Project context is descriptive. Browse and preview are read-only here'))
  assert.ok(picker.includes('isAttached={receipt => {'))
  assert.ok(picker.includes('localGitSavedCopies.adoptAttachments(savedCopyScope, attachments.map(item => item.id))'))
  assert.ok(picker.includes('localGitSavedCopies.submit(savedCopyScope, connection.id, receipt'))
  assert.ok(picker.includes("id: savedId, label: path, kind: 'file', source: UI_HOST_SOURCE, previewText: text"))
  assert.ok(picker.includes('attachments.some(item => item.id === savedId)'))
  assert.ok(!/onAttach=\{[^}]*captureLocalFolder/.test(picker), 'selected-file attach never rereads the folder')
  assert.ok(workflow.includes('attachments={attachments} intentScope={intentScope} allowSavedCopies={referenceCopiesEnabled}'))
  assert.ok(workflow.includes('attachments: Attachment[]'))
  assert.ok(workflow.includes("localGitSavedCopies.acknowledgedIds(intentScope, attachments.map(item => item.id), 'folder').length"), 'folder footer counts only acknowledged folder-preview copies')
  assert.ok(picker.includes("localGitSavedCopies.id(savedCopyScope, connection.id, receipt, 'folder')"), 'folder receipt identity keeps source kind')
  assert.ok(picker.includes("}, 'folder')"), 'folder saved-copy intent is source-qualified at submission')
  assert.ok(workflow.includes('count={addedIds.length + acknowledgedSavedCopyCount}'))
})
